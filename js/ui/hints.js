"use strict";
/* ============================================================
   UI / HINTS — контекстные подсказки (приходят в свой момент)
   ============================================================ */

let hintTimer=null;
function hint(id,title,text){
  if (S.hints.includes(id)) return;
  S.hints.push(id);
  const c=$('#hintCard');
  c.innerHTML='<div class="ht">'+IC.moon+esc(title)+'</div><div class="hp">'+text+'</div><button class="hx">Понял</button>';
  c.classList.add('on');
  c.querySelector('.hx').onclick=()=>c.classList.remove('on');
  clearTimeout(hintTimer);
  hintTimer=setTimeout(()=>c.classList.remove('on'),16000);
  save(true);
}

/* Подсказки, зависящие от накопленного состояния */
setInterval(()=>{
  if (!S.cls) return;
  if (S.gold>=upgCost(SHOP[0])*1.2 && S.purchases===0)
    hint('shop','Лавка Теней','Золота хватает на первую покупку. Клинок усилит руку, Слуги Тьмы будут бить сами.');
  if ((S.res.ash||0)>=12 && !S.oil)
    hint('forge','Горн','Пепла хватит на первое масло. Во вкладке <b>Горн</b> варят эликсиры, смазывают клинок, чертят руны и перековывают надетое.');
  if ((S.res.whisper||0)>=1)
    hint('whisper','Шёпот','Шёпот копится, пока тебя нет, и капает от свиты. Он оплачивает Колодец, чернила и Тихий Час — во вкладке <b>Дела</b>.');
  if (Object.keys(S.pets).length>=1 && S.maxStage>=15)
    hint('exped','Экспедиции','Фамильяра можно отправить в темноту. Он не будет усиливать тебя, пока не вернётся, — зато принесёт Пепел, Кровь и Шёпот. Вкладка <b>Дела</b>.');
  if (S.maxStage>=30 && S.prestige===0)
    hint('prestSoon','Оковы звенят','На глубине '+PREST_REQ+' ты сможешь разорвать цепь: потерять всё ради Осколков Проклятия, которые не сгорают никогда.');
  if (S.maxStage>=PREST_REQ && S.prestige===0)
    hint('prestReady','Цепь поддаётся','Разрыв доступен во вкладке <b>Тьма</b>. Первый разрыв щедрее прочих в 2.6 раза — и после него ты станешь сильнее, чем был.');
  if (S.prestige>=1)
    hint('ult','Ультиматив','После первой смерти ты вспомнил кое-что большее. Круглая кнопка справа на панели умений — твой ультиматив. Клавиша 3.');
  if (S.prestige>=1 && S.shards>0)
    hint('dark','Вечная Тьма','Осколки вплетаются в древо: Ярость, Алчность, Вечность. Эти узлы не исчезают ни при одном разрыве.');
  if (S.prestige>=2 && !S.sub)
    hint('subSoon','Третья смерть','Следующий Разрыв Оков откроет подкласс — он даст не проценты, а собственную боевую механику.');
  if (S.prestige>=4)
    hint('tn','Истинное Имя','После пяти разрывов и пяти Осколков Истины ты сможешь назвать себя заново. Это откроет последнюю скрытую глубину.');
}, 2500);
